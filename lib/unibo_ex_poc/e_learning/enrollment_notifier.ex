defmodule UniboV4.ELearning.Enrollment.Notifier do
  use Ash.Notifier

  @impl true
  def notify(%Ash.Notifier.Notification{action: %{name: action_name}} = notification) do
    topic = case action_name do
      :join -> "elearning.enrollment.joined"
      :recompute_completion -> "elearning.enrollment.progress_updated"
      _ -> nil
    end

    if topic do
      Phoenix.PubSub.broadcast(UniboV4.PubSub, topic, {action_name, notification.data})
    end

    :ok
  end
end
