defmodule UniboV4.Lunch.LunchSupplier.Notifier do
  use Ash.Notifier

  @impl true
  def notify(%Ash.Notifier.Notification{action: %{name: action_name}} = notification) do
    topic = case action_name do
      :send_orders -> "lunch.supplier.orders_sent"
      :confirm_orders -> "lunch.supplier.orders_confirmed"
      _ -> nil
    end

    if topic do
      Phoenix.PubSub.broadcast(UniboV4.PubSub, topic, {action_name, notification.data})
    end

    :ok
  end
end
