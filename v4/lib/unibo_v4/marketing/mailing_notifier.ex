defmodule UniboV4.Marketing.Mailing.Notifier do
  use Ash.Notifier

  @impl true
  def notify(%Ash.Notifier.Notification{action: %{name: action_name}} = notification) do
    topic = case action_name do
      :launch -> "marketing.mailing.launched"
      :schedule -> "marketing.mailing.scheduled"
      :cancel -> "marketing.mailing.cancelled"
      _ -> nil
    end

    if topic do
      Phoenix.PubSub.broadcast(UniboV4.PubSub, topic, {action_name, notification.data})
    end

    :ok
  end
end
