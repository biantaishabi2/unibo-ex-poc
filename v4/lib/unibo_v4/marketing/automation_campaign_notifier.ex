defmodule UniboV4.Marketing.AutomationCampaign.Notifier do
  use Ash.Notifier

  @impl true
  def notify(%Ash.Notifier.Notification{action: %{name: action_name}} = notification) do
    topic = case action_name do
      :start_campaign -> "marketing.automation.campaign.started"
      :stop_campaign -> "marketing.automation.campaign.stopped"
      _ -> nil
    end

    if topic do
      Phoenix.PubSub.broadcast(UniboV4.PubSub, topic, {action_name, notification.data})
    end

    :ok
  end
end
