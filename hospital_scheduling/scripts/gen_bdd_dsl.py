#!/usr/bin/env python3
"""
从 priv/bdd/sources/<domain>/*.yaml 重新生成 docs/bdd/features/<MODULE>.dsl

按 module 分组，每个 module 一个 .dsl 文件（与现有结构一致）。
"""

import os
import sys
import yaml
from pathlib import Path
from collections import defaultdict

def yaml_load(path):
    with open(path, 'r', encoding='utf-8') as f:
        return yaml.safe_load(f)

def edge_class_to_tag(edge_class: str) -> str:
    mapping = {
        'action_contract': 'seed action_contract',
        'event_contract': 'seed event_contract',
        'workflow_contract': 'seed workflow_contract',
        'integration_contract': 'seed integration_contract',
        'determination_contract': 'seed determination_contract',
        'graphql_contract': 'graphql',
    }
    return mapping.get(edge_class, 'seed')

def build_scenario_steps(data: dict, filename: str) -> list:
    steps = []
    edge_class = data.get('edge_class', '')
    module = data.get('module', '')
    file_id = filename.replace('.yaml', '')

    if edge_class == 'graphql_contract':
        # runtime 会自动添加 _bdd 后缀，所以 id 需要去掉 _bdd
        seed_id = file_id
        if seed_id.endswith('_bdd'):
            seed_id = seed_id[:-4]
        steps.append(f'GIVEN given_seed_context id="{seed_id}" module="{module}"')
        steps.append(f'GIVEN given_graphql_schema_loaded module="{module}"')
        steps.append(f'WHEN when_introspect_graphql_fields module="{module}"')
        steps.append(f'THEN then_graphql_contract_should_hold module="{module}"')
    else:
        steps.append(f'GIVEN given_seed_context id="{file_id}" module="{module}"')
        steps.append(f'WHEN when_execute_seed_contract module="{module}"')
        steps.append(f'THEN then_seed_contract_should_hold module="{module}"')

    return steps

def main():
    project_root = Path(__file__).resolve().parent.parent
    sources_root = project_root / 'priv' / 'bdd' / 'sources'
    docs_bdd_root = project_root / 'docs' / 'bdd' / 'features'

    if not sources_root.exists():
        print(f"错误: sources 目录不存在: {sources_root}", file=sys.stderr)
        sys.exit(1)

    docs_bdd_root.mkdir(parents=True, exist_ok=True)

    # 收集所有 source，按 module 分组
    module_sources = defaultdict(list)
    domains = sorted([d.name for d in sources_root.iterdir() if d.is_dir()])

    for domain in domains:
        source_dir = sources_root / domain
        for yf in sorted(source_dir.glob('*.yaml')):
            try:
                data = yaml_load(yf)
                edge_class = data.get('edge_class', '')
                if not edge_class:
                    continue
                module = data.get('module', '')
                if not module:
                    continue
                module_sources[module].append((yf.name, data))
            except Exception as e:
                print(f"  警告: 解析 {yf} 失败: {e}", file=sys.stderr)

    print(f"发现 {len(module_sources)} 个模块，共 {sum(len(v) for v in module_sources.values())} 个场景")

    # 按 module 生成 DSL
    for module in sorted(module_sources.keys()):
        items = module_sources[module]
        out_file = docs_bdd_root / f"{module}.dsl"

        lines = []
        lines.append(f'# Generated by: scripts/gen_bdd_dsl.py')
        lines.append('')

        # 按 edge_class 分组
        groups = defaultdict(list)
        for filename, data in items:
            groups[data['edge_class']].append((filename, data))

        for filename, data in items:
            edge_class = data.get('edge_class', '')
            file_id = filename.replace('.yaml', '')
            tag = edge_class_to_tag(edge_class)
            contract = data.get('contract', f'{module} contract seed scenario')

            scenario_id = f"BDD-{module}-SEED-{file_id}"
            lines.append(f'[SCENARIO: {scenario_id}] TITLE: {contract} TAGS: {tag}')

            steps = build_scenario_steps(data, filename)
            for step in steps:
                lines.append(step)
            lines.append('')

        out_file.write_text('\n'.join(lines), encoding='utf-8')
        print(f"  {out_file.name}: {len(items)} 场景")

    print(f"\n完成！DSL 文件已生成到 {docs_bdd_root}")

if __name__ == '__main__':
    main()
